// Generates the licensing records for the third-party libraries upstream
// vendored in legacy/webapp/libs/, from ONE source table:
// tools/data/legacy-libs.json (the licence audit, ADR-0005).
//
//   - REUSE.toml: the block between the BEGIN/END markers.
//   - docs/legacy-libraries.md: a human-readable audit table with evidence.
//
// One table, two outputs, so the machine-readable and human-readable records
// can never disagree.
//
// It also GUARDS the table against the files themselves (--check and normal runs).
// Every tracked file under legacy/webapp/libs/ must match a row, and each file is
// scanned IN FULL for a GPL-family notice. Many vendored files are bundles of
// concatenated modules, so a notice needn't sit at the top (reviewer, #4). A notice the row
// doesn't account for fails: the row's SPDX must name a GPL-family licence, or the
// row must carry an explicit `election` note (e.g. dual MIT/GPL, MIT elected).
// This exists because a first audit recorded four AGPL-3.0 Ace modes as BSD. A
// check that only compares generated text never reads a header.
//
//   node tools/gen-legacy-licences.mjs          rewrite both files (after guarding)
//   node tools/gen-legacy-licences.mjs --check  exit 1 if stale or unguarded (CI)

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { libraries: libs, removed } = JSON.parse(
  readFileSync(join(root, 'tools/data/legacy-libs.json'), 'utf8'),
);
const check = process.argv.includes('--check');

const LIBS_DIR = 'legacy/webapp/libs/';
const GPL_NOTICE = /affero|general public licen[cs]e|(^|[^a-z])l?gpl([^a-z]|$)/i;
const GPL_SPDX = /GPL/;

const BEGIN = '# BEGIN legacy-libs (generated by tools/gen-legacy-licences.mjs; do not edit)';
const END = '# END legacy-libs';

const toml = (s) => JSON.stringify(s); // TOML basic strings share JSON's escaping for this data

// ── Guard: the table must be true of the files ────────────────────────────
// REUSE glob semantics: `**` matches across directories, `*` does not.
const globRe = (g) =>
  new RegExp(
    '^' +
      g
        .split('**')
        .map((part) => part.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '[^/]*'))
        .join('.*') +
      '$',
  );
const rowMatchers = libs.map((l) => ({ lib: l, res: l.paths.map(globRe) }));

function guard() {
  const problems = [];
  const files = execFileSync('git', ['ls-files', '-z', '--', LIBS_DIR], { cwd: root })
    .toString()
    .split('\0')
    .filter(Boolean);
  for (const f of files) {
    // Later annotations win in REUSE.toml, so the LAST matching row governs.
    const row = rowMatchers.filter((m) => m.res.some((re) => re.test(f))).at(-1)?.lib;
    if (!row) {
      problems.push(`${f}: no row in tools/data/legacy-libs.json covers this file`);
      continue;
    }
    const text = readFileSync(join(root, f), 'utf8');
    if (GPL_NOTICE.test(text) && !GPL_SPDX.test(row.spdx) && !row.election) {
      problems.push(
        `${f}: contains a GPL-family notice, but row "${row.name}" records ${row.spdx} with no election note`,
      );
    }
  }
  for (const r of removed) {
    for (const p of r.paths)
      if (files.includes(p)) problems.push(`${p}: listed as removed but still tracked`);
  }
  return { problems, count: files.length };
}

// ── Outputs ───────────────────────────────────────────────────────────────
function reuseBlock() {
  const blocks = libs.map((l) =>
    [
      `# ${l.name} ${l.version}`,
      '[[annotations]]',
      `path = [${l.paths.map(toml).join(', ')}]`,
      'precedence = "override"',
      `SPDX-FileCopyrightText = ${toml(l.copyright)}`,
      `SPDX-License-Identifier = ${toml(l.spdx)}`,
    ].join('\n'),
  );
  return [BEGIN, ...blocks, END].join('\n\n');
}

function auditDoc() {
  const esc = (s) => s.replaceAll('|', '\\|');
  const short = (p) => `\`${p.replace(LIBS_DIR, '')}\``;
  const rows = libs.map(
    (l) =>
      `| ${esc(l.name)} | ${esc(l.version)} | \`${l.spdx}\` | ${l.paths.map(short).join(', ')} | ${esc(l.election ?? l.evidence)} |`,
  );
  const removedRows = removed.map(
    (r) =>
      `| ${r.paths.map(short).join(', ')} | ${esc(r.licence)} | ${r.date} | ${esc(r.reason)} |`,
  );
  return `<!--
SPDX-FileCopyrightText: 2026 Promotional Notions Pty Ltd trading as Woodpatch House & Garden
SPDX-License-Identifier: MIT
-->

# Licences of upstream's vendored libraries

Generated by \`tools/gen-legacy-licences.mjs\` from \`tools/data/legacy-libs.json\`. Do not edit by hand.

Upstream webgcode vendored third-party libraries in \`legacy/webapp/libs/\`. They are
redistributed here as received from upstream, each under its own licence, **except the files
listed under "Removed"**. None of them is built, bundled, published or served by this project
(ADR-0005). The audit was done on 2026-09-25. Where a file carries a licence header, that header
governs; where it doesn't, the licence comes from the library's own project.

**Counting.** The \`libs/\` directory has 38 top-level entries. They are grouped here into
${libs.length} rows: one row per library, where a library's files may be several top-level
entries (e.g. RequireJS and its text plugin). Font Awesome takes two rows, because its fonts
and its CSS are under different licences.

**Guard.** CI reads every file covered here in full, and fails when a GPL-family notice
anywhere in it isn't accounted for by the row's licence or by an explicit election note.

| Library | Version | SPDX | Files | Evidence |
| ------- | ------- | ---- | ----- | -------- |
${rows.join('\n')}

## Re-vendoring and the private-refs check

The CI check against references to private work (\`.github/ci/private-refs.mjs\`) scans only
the lines a PR adds, so the vendored files above pass as they are. Re-vendoring one adds
all its lines again. Two lines of \`opentype.js\` (Adobe Tech Note references, \`#\` with
a 5000s number) would then be flagged. Rephrase nothing in a vendored file: note the hit
on the PR, and have the maintainer approve it.

## Removed

| Files | Licence | Removed | Reason |
| ----- | ------- | ------- | ------ |
${removedRows.join('\n')}
`;
}

function spliceReuse(current) {
  const a = current.indexOf(BEGIN);
  const b = current.indexOf(END);
  if (a === -1 || b === -1) throw new Error('REUSE.toml is missing the legacy-libs markers');
  return current.slice(0, a) + reuseBlock() + current.slice(b + END.length);
}

const { problems, count } = guard();
for (const p of problems) console.error(`licence guard: ${p}`);
if (problems.length) {
  console.error(`${problems.length} licence problem(s) in ${count} vendored files`);
  process.exit(1);
}

const reusePath = join(root, 'REUSE.toml');
const docPath = join(root, 'docs/legacy-libraries.md');
const outputs = [
  [reusePath, spliceReuse(readFileSync(reusePath, 'utf8'))],
  [docPath, auditDoc()],
];

let stale = false;
for (const [path, want] of outputs) {
  let have = '';
  try {
    have = readFileSync(path, 'utf8');
  } catch {
    // missing file counts as stale
  }
  if (have === want) continue;
  if (check) {
    console.error(`stale: ${path.slice(root.length + 1)} (run node tools/gen-legacy-licences.mjs)`);
    stale = true;
  } else {
    writeFileSync(path, want);
    console.log(`wrote ${path.slice(root.length + 1)}`);
  }
}
process.exit(stale ? 1 : 0);
